CREATE TABLE IF NOT EXISTS dominio (
    id INTEGER PRIMARY KEY,
    tipo VARCHAR(40) NOT NULL,
    chave VARCHAR(30) NOT NULL,
    nome VARCHAR(70) NOT NULL,
    UNIQUE (tipo, chave)
);

CREATE TABLE IF NOT EXISTS estado (
    sigla CHAR(2) PRIMARY KEY,
    nome VARCHAR(60) NOT NULL
);

CREATE SEQUENCE IF NOT EXISTS fornecedor_codigo START WITH 1 MAXVALUE 999999999;

CREATE TABLE IF NOT EXISTS fornecedor (
    codigo VARCHAR(10) PRIMARY KEY,
    razao_social VARCHAR(100) NOT NULL,
    nome_fantasia VARCHAR(60) NOT NULL,
    cnpj CHAR(14) NOT NULL UNIQUE,
    email VARCHAR(100) NOT NULL,
    status VARCHAR(7) NOT NULL CHECK (status IN ('ATIVO', 'INATIVO')),
    usuario VARCHAR(100) NOT NULL,
    dt_cadastro TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS telefone (
    fornecedor_codigo VARCHAR(10) PRIMARY KEY REFERENCES fornecedor(codigo),
    tipo_id INTEGER NOT NULL REFERENCES dominio(id),
    ddd CHAR(2) NOT NULL,
    numero VARCHAR(9) NOT NULL
);

CREATE TABLE IF NOT EXISTS endereco (
    fornecedor_codigo VARCHAR(10) PRIMARY KEY REFERENCES fornecedor(codigo),
    tipo_id INTEGER NOT NULL REFERENCES dominio(id),
    logradouro VARCHAR(100) NOT NULL,
    numero VARCHAR(10) NOT NULL,
    complemento VARCHAR(60),
    bairro VARCHAR(60) NOT NULL,
    cep CHAR(8) NOT NULL,
    cidade VARCHAR(60) NOT NULL,
    estado_sigla CHAR(2) NOT NULL REFERENCES estado(sigla),
    pais_id INTEGER NOT NULL REFERENCES dominio(id)
);

CREATE TABLE IF NOT EXISTS fornecedor_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fornecedor_codigo VARCHAR(10) NOT NULL REFERENCES fornecedor(codigo),
    operacao VARCHAR(15) NOT NULL CHECK (operacao IN ('INCLUSAO', 'ALTERACAO', 'INATIVACAO', 'ATIVACAO')),
    data_hora TIMESTAMP NOT NULL,
    usuario VARCHAR(100) NOT NULL,
    dados_antes TEXT,
    dados_depois TEXT NOT NULL,
    justificativa VARCHAR(255),
    categoria_inativacao_id INTEGER REFERENCES dominio(id),
    categoria_ativacao_id INTEGER REFERENCES dominio(id),
    CHECK (
        (operacao IN ('INCLUSAO', 'ALTERACAO') AND justificativa IS NULL
            AND categoria_inativacao_id IS NULL AND categoria_ativacao_id IS NULL)
        OR (operacao = 'INATIVACAO' AND justificativa IS NOT NULL AND btrim(justificativa) <> ''
            AND categoria_inativacao_id IS NOT NULL AND categoria_ativacao_id IS NULL)
        OR (operacao = 'ATIVACAO' AND justificativa IS NOT NULL AND btrim(justificativa) <> ''
            AND categoria_ativacao_id IS NOT NULL AND categoria_inativacao_id IS NULL)
    )
);

CREATE INDEX IF NOT EXISTS fornecedor_log_codigo_idx ON fornecedor_log (fornecedor_codigo);

CREATE OR REPLACE VIEW fornecedores_ativos_estoque AS
SELECT codigo, razao_social, nome_fantasia, cnpj
FROM fornecedor
WHERE status = 'ATIVO';

CREATE SCHEMA IF NOT EXISTS fornecedores_auth;

CREATE TABLE IF NOT EXISTS fornecedores_auth.spring_session (
    primary_id CHAR(36) PRIMARY KEY,
    session_id CHAR(36) NOT NULL UNIQUE,
    creation_time BIGINT NOT NULL,
    last_access_time BIGINT NOT NULL,
    max_inactive_interval INTEGER NOT NULL,
    expiry_time BIGINT NOT NULL,
    principal_name VARCHAR(100)
);

CREATE INDEX IF NOT EXISTS spring_session_expiry_idx
    ON fornecedores_auth.spring_session (expiry_time);

CREATE TABLE IF NOT EXISTS fornecedores_auth.spring_session_attributes (
    session_primary_id CHAR(36) NOT NULL
        REFERENCES fornecedores_auth.spring_session(primary_id) ON DELETE CASCADE,
    attribute_name VARCHAR(200) NOT NULL,
    attribute_bytes BYTEA NOT NULL,
    PRIMARY KEY (session_primary_id, attribute_name)
);
